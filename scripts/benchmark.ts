/**
 * Reproducible measurements behind the README tables:
 *  1. Calibration: how often each mode flags a "regression" when there is none (false
 *     positive rate) and when there is a real drop (power), from seeded simulations.
 *  2. Runtime of the full analysis at several sample sizes.
 * Run with: npm run bench   (writes benchmarks/results.md and prints it)
 */
import { writeFileSync } from 'node:fs'
import { performance } from 'node:perf_hooks'
import { analyze, analyzeMetric } from '../src/analyze'
import { mulberry32 } from '../src/random'
import type { ExampleRecord, GateConfig, ResultSet } from '../src/types'

const TRIALS = 2000

function gate(overrides: Partial<GateConfig>): GateConfig {
  return {
    metrics: [],
    maxDrop: {},
    defaultMaxDrop: 0,
    lowerIsBetter: new Set(),
    alpha: 0.05,
    confidenceLevel: 0.95,
    mode: 'significance',
    // The pass/fail decision does not use the bootstrap, so calibration runs use few resamples.
    bootstrapSamples: 100,
    seed: 1,
    topRegressions: 5,
    ...overrides
  }
}

function normal(rand: () => number): number {
  const u = 1 - rand()
  const v = rand()
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v)
}

/** Paired binary outcomes: 80% of items keep their baseline outcome, the rest are redrawn. */
function binaryPair(rand: () => number, n: number, drop: number): [number[], number[]] {
  const p = 0.8
  const redraw = 0.2
  const q = p - drop / redraw
  const b: number[] = []
  const c: number[] = []
  for (let i = 0; i < n; i++) {
    const x = rand() < p ? 1 : 0
    b.push(x)
    c.push(rand() < redraw ? (rand() < q ? 1 : 0) : x)
  }
  return [b, c]
}

/** Paired continuous scores with per-item noise (SD 0.15) and a mean shift of -drop. */
function continuousPair(rand: () => number, n: number, drop: number): [number[], number[]] {
  const b: number[] = []
  const c: number[] = []
  for (let i = 0; i < n; i++) {
    const x = 0.7 + 0.15 * normal(rand)
    b.push(x)
    c.push(x - drop + 0.15 * normal(rand))
  }
  return [b, c]
}

function rate(
  kind: 'binary' | 'continuous',
  n: number,
  drop: number,
  config: GateConfig,
  seed: number
): number {
  const rand = mulberry32(seed)
  let flagged = 0
  for (let t = 0; t < TRIALS; t++) {
    const [b, c] = kind === 'binary' ? binaryPair(rand, n, drop) : continuousPair(rand, n, drop)
    if (analyzeMetric('m', b, c, config).regressed) flagged++
  }
  return flagged / TRIALS
}

function pct(x: number): string {
  return `${(x * 100).toFixed(1)}%`
}

const lines: string[] = []
lines.push('# Benchmark results', '')
lines.push(
  `Generated by \`npm run bench\` on Node ${process.version} (${process.platform}/${process.arch}).`,
  ''
)
lines.push('## Calibration', '')
lines.push(
  `Share of ${TRIALS} seeded simulated PRs flagged as a regression. "Null" rows have no true change, so the`,
  'rate is the false positive rate. Binary: 80% base accuracy, 20% of items redrawn per run.',
  'Continuous: per-item score noise SD 0.15. Significance mode uses alpha = 0.05 and max-drop = 0.',
  ''
)
lines.push(
  '| Metric | n | True drop | Threshold mode, max-drop 0 | Threshold mode, max-drop 0.02 | Significance mode |'
)
lines.push('|---|---:|---:|---:|---:|---:|')
let seed = 100
for (const kind of ['binary', 'continuous'] as const) {
  for (const n of [200, 1000]) {
    for (const drop of [0, 0.02, 0.05]) {
      seed++
      const t0 = rate(kind, n, drop, gate({ mode: 'threshold' }), seed)
      const t2 = rate(kind, n, drop, gate({ mode: 'threshold', defaultMaxDrop: 0.02 }), seed)
      const sig = rate(kind, n, drop, gate({ mode: 'significance' }), seed)
      lines.push(
        `| ${kind} | ${n} | ${drop === 0 ? '0 (null)' : drop.toFixed(2)} | ${pct(t0)} | ${pct(t2)} | ${pct(sig)} |`
      )
    }
  }
}
lines.push('')

function syntheticSet(name: string, n: number, rand: () => number, shift: number): ResultSet {
  const records = new Map<string, ExampleRecord>()
  for (let i = 0; i < n; i++) {
    const id = `ex-${i}`
    records.set(id, {
      id,
      metrics: {
        exact_match: rand() < 0.8 - shift ? 1 : 0,
        f1: Math.min(1, Math.max(0, 0.7 - shift + 0.2 * normal(rand)))
      },
      latencyMs: 300 + 400 * rand(),
      costUsd: 0.0005 * (1 + rand())
    })
  }
  return { source: name, records }
}

lines.push('## Runtime', '')
lines.push(
  'Full `analyze` call (2 metrics, latency, cost, top regressions) with the default 10,000 bootstrap resamples. Median of 5 runs.',
  ''
)
lines.push('| Examples | Median time (ms) |', '|---:|---:|')
for (const n of [100, 1000, 10000, 50000]) {
  const rand = mulberry32(n)
  const base = syntheticSet('b', n, rand, 0)
  const cand = syntheticSet('c', n, rand, 0.01)
  const config = gate({ bootstrapSamples: 10000 })
  const times: number[] = []
  for (let r = 0; r < 5; r++) {
    const start = performance.now()
    analyze(base, cand, config)
    times.push(performance.now() - start)
  }
  times.sort((a, b) => a - b)
  lines.push(`| ${n.toLocaleString('en-US')} | ${(times[2] as number).toFixed(1)} |`)
}
lines.push('')

const output = lines.join('\n')
writeFileSync('benchmarks/results.md', output)
console.log(output)
